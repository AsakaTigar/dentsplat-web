// tools/sha-assets.mjs — digests + provenance table for the shipped splat packets.
//
// Every number that goes into MEASUREMENTS.md or the Technical Brief has to be traceable to a
// specific byte sequence, otherwise "measured" is just a style choice. This prints the table that
// anchors the claims: which asset, how many splats, how many bytes, sha256, and the pruning recipe
// that is embedded in the packet's own header (the viewer reads the same field a reviewer can grep).
//
//   node tools/sha-assets.mjs            # table to stdout
//   node tools/sha-assets.mjs --write    # also refresh tools/out/PROVENANCE.md
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, writeFileSync, existsSync, statSync } from 'node:fs';
import { join } from 'node:path';

const DIR = process.argv.includes('--dir') ? process.argv[process.argv.indexOf('--dir') + 1] : 'public/assets';
const OUT = 'tools/out/PROVENANCE.md';
const files = readdirSync(DIR).sort();
const sha = (f) => createHash('sha256').update(readFileSync(join(DIR, f))).digest('hex');

// The .dspk header is followed by a JSON meta block; pull the prune recipe out of it the same way
// the decoder does, so the reported recipe is the one the browser actually loaded.
function pruneRecipe(f) {
  const buf = readFileSync(join(DIR, f));
  const s = buf.toString('latin1');
  const i = s.indexOf('"prune":');
  if (i < 0) return null;
  const start = s.indexOf('{', i);
  let depth = 0, end = start;
  for (; end < s.length; end++) {
    if (s[end] === '{') depth++;
    else if (s[end] === '}') { depth--; if (!depth) break; }
  }
  try { return JSON.parse(s.slice(start, end + 1)); } catch { return { parse_error: s.slice(start, end + 1).slice(0, 80) }; }
}

const report = existsSync(join(DIR, 'report.json')) ? JSON.parse(readFileSync(join(DIR, 'report.json'), 'utf8')) : null;
const sceneOf = { sceneA: 'sceneA_ios', sceneB: 'sceneB_cbct' };
const rows = [];
for (const f of files) {
  if (!f.endsWith('.dspk')) continue;
  const m = /^(scene[AB])_(full|pruned)\.dspk$/.exec(f);
  if (!m) { rows.push({ file: f, note: 'unexpected name' }); continue; }
  const scene = report?.scenes?.[sceneOf[m[1]]];
  const info = scene?.[m[2]];
  rows.push({
    file: f, bytes: statSync(join(DIR, f)).size, sha256: sha(f),
    splats: info?.splats, mb: info?.mb, sh: info ? `SH${info.sh_degree}` : '?',
    bps: info?.bytes_per_splat,
    gap: m[2] === 'pruned' && scene ? `${scene.compression_fidelity_mm.coverage_gap_mean} mm mean / p95 ${scene.compression_fidelity_mm.coverage_gap_p95} / max ${scene.compression_fidelity_mm.coverage_gap_max}` : '',
    recipe: m[2] === 'pruned' ? pruneRecipe(f) : null,
  });
}

const line = (r) => `${r.file}  ${String(r.bytes).padStart(9)} B  ${r.sha256.slice(0, 16)}…  ${r.splats ?? '-'} splats  ${r.sh ?? '-'}  ${r.bps ?? '-'} B/splat` +
  (r.gap ? `\n    coverage gap ${r.gap}` : '') +
  (r.recipe ? `\n    prune ${JSON.stringify(r.recipe)}` : '');

const body = rows.map(line).join('\n');
console.log(body);
console.log('\nnon-splat artefacts:');
for (const f of files) if (!f.endsWith('.dspk')) console.log(`  ${f.padEnd(20)} ${String(statSync(join(DIR, f)).size).padStart(9)} B  ${sha(f).slice(0, 16)}…`);
if (report?.generated) console.log(`\nreport.generated = ${report.generated}`);

if (process.argv.includes('--write')) {
  writeFileSync(OUT, [
    '# DentSplat asset provenance',
    '',
    `Generated by \`node tools/sha-assets.mjs --write\` in ${DIR}. Regenerating assets changes these`,
    'digests, and any measurement file that cites them must be re-run.',
    '',
    'Assets are a SYNTHETIC preview: the anatomy, arch metrics and FDI numbering come from the public',
    'Teeth3DS+ / ToothFairy3 statistics, the colour and lesion placement are procedural. Replacing them',
    'with trained packets is a file swap of the same contract (`pipeline/run_case.sh` -> PLY + labels ->',
    '`tools/ply2dspk.ts`), no frontend change.',
    '',
    '```',
    body,
    '```',
    '',
    '```',
    ...files.filter((f) => !f.endsWith('.dspk')).map((f) => `${f.padEnd(20)} ${String(statSync(join(DIR, f)).size).padStart(9)} B  ${sha(f)}`),
    '```',
    '',
  ].join('\n'), 'utf8');
  console.log(`\n[OK] wrote ${OUT}`);
}
